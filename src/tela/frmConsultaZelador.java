    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
         
        int linha = tabConsultaZelador.getSelectedRow();
        
        if(linha == -1){
          JOptionPane.showMessageDialog(this, "Selecione um zelador da tabela para alterar");
          return;
        }
        
        
        int id = Integer.parseInt(tabConsultaZelador.getValueAt(linha, 0).toString());
        
        
        String nome = txtNome.getText().trim();
        String especialidade = txtEspecialidade.getText().trim();
        String telefone = txtTelefone.getText().trim();
        String email = txtEmail.getText().trim();
        
        
        if (nome.isEmpty() || especialidade.isEmpty() || telefone.isEmpty() || email.isEmpty()){
          JOptionPane.showMessageDialog(this, "Preencha todos os campos");
          return;
        }
        
        
        
        int resposta = JOptionPane.showConfirmDialog(this, "Deseja alterar os dados do zelador de ID " + id + " ?", "Confirmar alteracao", JOptionPane.YES_NO_CANCEL_OPTION, JOptionPane.QUESTION_MESSAGE);
        if( resposta != JOptionPane.YES_OPTION){
          return;
        }
        
        
        
        String sql = """
                     UPDATE zelador SET nome = ?, especialidade = ?, telefone = ?, email = ? WHERE id = ?
                     """;
        
        try(Connection conex = Conexao.conectar();
             PreparedStatement stmt = conex.prepareStatement(sql)){
         
         stmt.setString(1, nome);
         stmt.setString(2, especialidade);
         stmt.setString(3, telefone);
         stmt.setString(4, email);
         stmt.setInt(5, id);
         
         
         int registros = stmt.executeUpdate();
         if(registros > 0){
           JOptionPane.showMessageDialog(this, "Zelador alterado com sucesso!");
           atualizarTabela();
           txtID.setText("");
           txtNome.setText("");
           txtEspecialidade.setText("");
           txtTelefone.setText("");
           txtEmail.setText("");
         }else {
           JOptionPane.showMessageDialog(this, "Zelador nao encontrado");
         }
        }catch(SQLException erro){
          JOptionPane.showMessageDialog(this, "Erro ao alterar zelador: " + erro.getMessage());
        }
    }//GEN-LAST:event_btnAlterarActionPerformed

