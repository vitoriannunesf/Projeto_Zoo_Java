    private void btnLocalizarZeladorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLocalizarZeladorActionPerformed
        String pesquisa = txtPesquisarZelador.getText().trim();
        if (pesquisa.isEmpty()){
           JOptionPane.showMessageDialog(this, "Digite o nome do zelador aqui", "Pequisa Vazia", JOptionPane.WARNING_MESSAGE);
           return;
        }
        
        DefaultTableModel modelo = (DefaultTableModel) tabConsultaZelador.getModel();
        
        modelo.setRowCount(0);
        
        String sql = "SELECT * FROM zelador " + "WHERE nome ILIKE ? " + "ORDER BY nome";
        
        try(Connection conex = Conexao.conectar();
            PreparedStatement stmt = conex.prepareStatement(sql)){
        stmt.setString(1,"%" + pesquisa + "%");
        
           try(ResultSet resultado = stmt.executeQuery()){
              while (resultado.next()){
                modelo.addRow(new Object [] {
                  resultado.getInt("id"),
                  resultado.getString("nome"),
                  resultado.getString("especialidade"),
                  resultado.getString("telefone"),
                  resultado.getString("email")});
              }
           
           }
           if(modelo.getRowCount() == 0){
            JOptionPane.showMessageDialog(this, "Nenhum zelador encontrado para: " + pesquisa, "Resultado da pesquisa", JOptionPane.INFORMATION_MESSAGE);
           }
        }catch(SQLException erro){
          JOptionPane.showMessageDialog(this, "Erro ao localizar zelador: \n" + erro.getMessage(), "Erro no banco de dados", JOptionPane.ERROR_MESSAGE);
        }
                                 
    }//GEN-LAST:event_btnLocalizarZeladorActionPerformed

