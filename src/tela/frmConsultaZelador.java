    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linha = tabConsultaZelador.getSelectedRow();
        
        if(linha == -1){
          JOptionPane.showMessageDialog(this, "Selecione um zelador para excluir");
          return;
        }
        
        int id = Integer.parseInt(tabConsultaZelador.getValueAt(linha, 0).toString());
        
        int  resposta = JOptionPane.showConfirmDialog(this,"Deseja realmente excluir o zelador do id " + id + " ?", "Confirmar Exclusão", JOptionPane.YES_NO_CANCEL_OPTION, JOptionPane.QUESTION_MESSAGE);
        
        if(resposta != JOptionPane.YES_OPTION){
          return;
        }
        
        String sql = "DELETE FROM zelador WHERE id = ?";
        
        try(Connection conex = Conexao.conectar();
             PreparedStatement stmt = conex.prepareStatement(sql)){
          
            stmt.setInt(1, id);
            
            int registros = stmt.executeUpdate();
            if(registros > 0){
               JOptionPane.showMessageDialog(this, "Zelador excluido com sucesso!");
               atualizarTabela();
            } else{
               JOptionPane.showMessageDialog(this, "Zelador nao encontrado");
            }
        } catch(SQLException erro){
           JOptionPane.showMessageDialog(this, "Erro ao excluir zelador: " + erro.getMessage());
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

