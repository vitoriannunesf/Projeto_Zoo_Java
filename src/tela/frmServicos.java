    private void atualizarTabela(){
      DefaultTableModel modelo = (DefaultTableModel) tblServicos.getModel();
        modelo.setRowCount(0);
        
        String sql = "SELECT s.id, s.animal_id, a.nome AS animal_nome, "
                   + "s.zelador_id, z.nome AS zelador_nome, "
                   + "s.descricao, s.data_execucao, s.executado "
                   + "FROM servico_zoo s "
                   + "INNER JOIN animal a ON a.id = s.animal_id "
                   + "INNER JOIN zelador z ON z.id = s.zelador_id "
                   + "ORDER BY s.id";
        try(Connection conex = Conexao.conectar();
               PreparedStatement stmt = conex.prepareStatement(sql);
               ResultSet rs = stmt.executeQuery()){
         while (rs.next()){
            modelo.addRow(new Object []{
              rs.getInt("id"),
              rs.getInt("animal_id"),
              rs.getString("animal_nome"),
              rs.getInt("zelador_id"),
              rs.getString("zelador_nome"),
              rs.getString("descricao"),
              rs.getDate("data_execucao"),
              rs.getBoolean("executado")? "SIM" : "NÃO"});
         
            }
           
        }catch(SQLException erro){
          JOptionPane.showMessageDialog(this, "Erro ao carregar servicos " + erro.getMessage());
        }
        
        
        for(int i = 0; i < tblServicos.getColumnCount(); i++){
          
            tblServicos.getColumnModel().getColumn(i).setCellRenderer(
             new javax.swing.table.DefaultTableCellRenderer(){
             
             @Override
             public java.awt.Component getTableCellRendererComponent(
               javax.swing.JTable table,
               Object value,
               boolean isSelected,
               boolean hasFocus,
               int row,
               int column) {
             java.awt.Component c = super.getTableCellRendererComponent(table, value, isSelected, hasFocus, row, column);
             
             int colunaExecutado = 7;
             
             int modelRow = table.convertRowIndexToModel(row);
             
             Object valor = table.getModel().getValueAt(modelRow, colunaExecutado);
             
             boolean concluido = "SIM".equalsIgnoreCase(String.valueOf(valor).trim());
             
             if(!isSelected){
               if(concluido) {
                 c.setBackground(new java.awt.Color(200, 255, 200));
               
               }else {
                c.setBackground(java.awt.Color.WHITE);
               }
               
             }else{
                c.setBackground(table.getSelectionBackground());
             }
            return c;
             
             }
             });
    }
   }
            
    
    
    
    
    
    
